const dicts = { ar, en };
export type TKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

export function makeT(locale: Locale) {
  const d = dicts[locale];
  const t = (key: TKey, vars?: Record<string, string | number>) => {
    let s = d[key] as string;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
  return Object.assign(t, { d, locale, err: (code: string) => d.errors[code] ?? d.errors.default });
}
export type T = ReturnType<typeof makeT>;
